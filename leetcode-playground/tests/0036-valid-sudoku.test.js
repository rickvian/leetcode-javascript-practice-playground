import { isValidSudoku } from '../0036-valid-sudoku';

describe('0036-valid-sudoku', () => {
    // Official LeetCode example 1 - valid partially-filled board
    it('should return true for valid partially-filled board (example 1)', () => {
        const board = [
            ["5","3",".",".","7",".",".",".","."],
            ["6",".",".","1","9","5",".",".","."],
            [".","9","8",".",".",".",".","6","."],
            ["8",".",".",".","6",".",".",".","3"],
            ["4",".",".","8",".","3",".",".","1"],
            ["7",".",".",".","2",".",".",".","6"],
            [".","6",".",".",".",".","2","8","."],
            [".",".",".","4","1","9",".",".","5"],
            [".",".",".",".","8",".",".","7","9"]
        ];
        expect(isValidSudoku(board)).toBe(true);
    });

    // Official LeetCode example 2 - invalid board (column conflict: 8 appears twice in column 0)
    it('should return false for invalid board (example 2)', () => {
        const board = [
            ["8","3",".",".","7",".",".",".","."],
            ["6",".",".","1","9","5",".",".","."],
            [".","9","8",".",".",".",".","6","."],
            ["8",".",".",".","6",".",".",".","3"],
            ["4",".",".","8",".","3",".",".","1"],
            ["7",".",".",".","2",".",".",".","6"],
            [".","6",".",".",".",".","2","8","."],
            [".",".",".","4","1","9",".",".","5"],
            [".",".",".",".","8",".",".","7","9"]
        ];
        expect(isValidSudoku(board)).toBe(false);
    });

    // All empty board - valid
    it('should return true for board with all empty cells', () => {
        const board = [
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."]
        ];
        expect(isValidSudoku(board)).toBe(true);
    });

    // Single number in board - valid
    it('should return true for board with only one filled cell', () => {
        const board = [
            ["5",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."]
        ];
        expect(isValidSudoku(board)).toBe(true);
    });

    // Row conflict - same digit appears twice in same row
    it('should return false for board with row conflict', () => {
        const board = [
            ["1",".",".",".",".",".",".",".","1"],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."]
        ];
        expect(isValidSudoku(board)).toBe(false);
    });

    // Column conflict - same digit appears twice in same column
    it('should return false for board with column conflict', () => {
        const board = [
            ["7",".",".",".",".",".",".",".","."],
            ["7",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."]
        ];
        expect(isValidSudoku(board)).toBe(false);
    });

    // 3x3 box conflict - same digit appears twice in same 3x3 box
    it('should return false for board with 3x3 box conflict', () => {
        const board = [
            ["3",".",".",".",".",".",".",".","."],
            [".","3",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."]
        ];
        expect(isValidSudoku(board)).toBe(false);
    });

    // Box conflict in middle box (rows 3-5, cols 3-5)
    it('should return false for conflict in a middle 3x3 box', () => {
        const board = [
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".","2",".",".",".","."],
            [".",".",".","2",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."]
        ];
        expect(isValidSudoku(board)).toBe(false);
    });

    // Valid board - each row/col/box has at most one of each digit
    it('should return true for a valid partially-filled board with scattered digits', () => {
        const board = [
            ["1",".",".","2",".",".","3",".","."],
            [".",".",".",".",".",".",".",".","1"],
            [".",".",".",".",".",".",".",".","."],
            ["2",".",".","3",".",".","4",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            ["3",".",".","4",".",".","5",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."]
        ];
        expect(isValidSudoku(board)).toBe(true);
    });

    // Board not required to be solvable - valid as long as no conflicts
    it('should return true for valid board that may not be solvable', () => {
        const board = [
            ["1",".",".",   "4",".",".",   "5",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            ["6",".",".",   "2",".",".",   "7",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."],
            ["8",".",".",   "9",".",".",   "3",".","."],
            [".",".",".",".",".",".",".",".","."],
            [".",".",".",".",".",".",".",".","."]
        ];
        expect(isValidSudoku(board)).toBe(true);
    });
});
